export type EntityId<R extends string> = string & { readonly __relation: R };
export type WireValue = { Bool: boolean } | { Int: string } | { Text: string } | { Ref: string } | { Decimal: string } | { Timestamp: string } | { Bytes: number[] };
export interface WireRow { id: string; fields: Record<string, WireValue> }
export interface Descriptor<T, R extends string> {
  readonly relation: R;
  readonly schemaId: string;
  readonly fingerprint: string;
  readonly fields: Readonly<Record<keyof T & string, FieldSpec>>;
  readonly insertSchema: Validator<T>;
  readonly updateSchema: Validator<Partial<T>>;
  readonly readSchema: Validator<{ id: EntityId<R>; data: T }>;
  encode(value: T): Record<string, WireValue>;
  encodePatch(value: Partial<T>): Record<string, WireValue>;
  decode(row: WireRow): { id: EntityId<R>; data: T };
}
export function defineRecord<T, R extends string>(relation: R, schemaId: string, fingerprint: string, fields: Readonly<Record<string, FieldSpec>>): Descriptor<T, R> {
  const insertSchema = objectValidator<T>(fields);
  const updateSchema = objectValidator<Partial<T>>(fields, true);
  const batchSchema = objectValidator<T>(fields, false, true);
  const batchPatch = objectValidator<Partial<T>>(fields, true, true);
  const readSchema = validator<{ id: EntityId<R>; data: T }>(input => {
    if (input === null || typeof input !== "object" || !("id" in input) || typeof input.id !== "string" || !uuidPattern.test(input.id) || !("data" in input)) return { success: false, issues: [{ code: "type", path: [], expected: "{id: UUID, data: record}", message: "invalid row" }] };
    const extra = Object.keys(input).filter(k => k !== "id" && k !== "data");
    if (extra.length) return { success: false, issues: extra.map(k => ({ code: "unknown_field", path: [k], expected: "id or data", message: "unknown field" })) };
    const result = insertSchema.safeParse(input.data);
    return result.success === true ? { success: true, data: { id: input.id as EntityId<R>, data: result.data } } : { success: false, issues: result.issues.map(i => ({ ...i, path: ["data", ...i.path] })) };
  });
  function encode(input: T | Partial<T>, partial: boolean): Record<string, WireValue> {
    const value = (partial ? batchPatch : batchSchema).parse(input) as Record<string, unknown>;
    return Object.fromEntries(Object.keys(value).map(name => {
      const kind = fields[name].kind; const v = value[name];
      const wire = ["Int", "Decimal", "Timestamp"].includes(kind) ? (v as bigint).toString() : kind === "Bytes" ? Array.from(v as Uint8Array) : v;
      return [name, { [kind]: wire } as WireValue];
    }));
  }
  return Object.freeze({ relation, schemaId, fingerprint, fields, insertSchema, updateSchema, readSchema,
    encode: (value: T) => encode(value, false), encodePatch: (value: Partial<T>) => encode(value, true),
    decode(row: WireRow) {
      if (!row || typeof row !== "object" || Object.keys(row).some(k => k !== "id" && k !== "fields") || !row.fields || typeof row.fields !== "object" || Array.isArray(row.fields)) throw new Error("invalid wire row");
      const data = Object.fromEntries(Object.entries(row.fields).map(([name, encoded]) => {
        if (!Object.hasOwn(fields, name)) throw new Error(`unknown wire field ${name}`);
        const kind: ScalarKind = fields[name].kind;
        if (!encoded || typeof encoded !== "object" || Object.keys(encoded).length !== 1 || !Object.hasOwn(encoded, kind)) throw new Error(`invalid wire field ${name}`);
        let v: unknown = (encoded as unknown as Record<string, unknown>)[kind];
        if (["Int", "Decimal", "Timestamp"].includes(kind)) {
          if (typeof v !== "string" || !/^-?(0|[1-9][0-9]*)$/.test(v) || v.length > 20) throw new Error(`invalid integer ${name}`);
          v = BigInt(v);
        } else if (kind === "Bytes") {
          if (!Array.isArray(v) || !v.every(n => Number.isInteger(n) && n >= 0 && n <= 255)) throw new Error(`invalid bytes ${name}`);
          v = Uint8Array.from(v);
        }
        return [name, v];
      }));
      return readSchema.parse({ id: row.id, data });
    }
  });
}
